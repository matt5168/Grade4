function handleChoiceSelect(selected, btnElement) {
  const correct = currentQuiz.expectedAnswer;
  const isCorrect = normalizeAnswer(selected) === normalizeAnswer(correct);
  const allBtns = document.querySelectorAll(".choice-btn");
  allBtns.forEach(b => b.disabled = true);
  
  const feedbackDiv = document.getElementById("quiz-feedback");
  
  if (isCorrect) {
    btnElement.classList.add("correct");
    feedbackDiv.innerHTML = `
      <div class="feedback correct">
        <div class="feedback-title">✅ 答對了！ / Correct!</div>
        <div class="en-text">Great job! ${correct}</div>
        <div class="cn-text">答對了！文法完全正確 / 提示：${currentQuiz.hintCn}</div>
      </div>
    `;
    speakText("Correct! Great job! " + correct);
  } else {
    btnElement.classList.add("wrong");
    // 標出正確的
    allBtns.forEach(b => {
      if (normalizeAnswer(b.textContent) === normalizeAnswer(correct) || b.innerText.includes(correct)) {
        // 用文字比對
        if (b.innerText.includes(correct.substring(0,10))) b.classList.add("correct");
      }
    });
    // 更精確：比對選項
    allBtns.forEach(b => {
      const txt = b.innerText.replace(/^[A-D]\s/, '').replace('🔊','').trim();
      if (normalizeAnswer(txt) === normalizeAnswer(correct)) b.classList.add("correct");
    });
    
    feedbackDiv.innerHTML = `
      <div class="feedback wrong">
        <div class="feedback-title">❌ 再試試 / Try Again</div>
        <div class="en-text">You chose: ${selected}</div>
        <div class="cn-text">你選的是：${selected}</div>
        <div style="margin-top:12px;">
          <strong>正確答案 / Correct Answer:</strong>
          <div class="correct-answer">${correct}</div>
          <div class="cn-text">💡 提示：${currentQuiz.hintCn}</div>
          <button id="btn-speak-correct" class="btn-small" style="margin-top:8px;">🔊 聽正確發音</button>
        </div>
      </div>
    `;
    const speakBtn = document.getElementById("btn-speak-correct");
    if (speakBtn) speakBtn.addEventListener("click", () => speakText(correct));
  }
  addSystemLog('[選擇題] 選擇: ' + selected + ' | 正確: ' + correct + ' | 結果: ' + (isCorrect ? '對' : '錯'));
}

